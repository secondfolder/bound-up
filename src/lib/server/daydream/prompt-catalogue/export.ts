import { createPatch } from 'diff';
import { type Catalogue, type Combo, LINT_RULE_LABELS } from '$lib/prompt-review';
import { BUILDERS, type Builder } from './axes';
import { buildCatalogue, paragraphContext, renderAll, reviewSelection, sweeps } from './enumerate';
import { promptText, renderPrompt } from './render';

/**
 * The committed snapshot of every prompt (`prompt-catalogue/` at the root;
 * docs/prompt-review.md): what `npm run prompts:export` writes and the
 * snapshot test compares, as a map of path to contents. Pure and
 * deterministic, so the same code always gives the same files and a change
 * in them is a change in a prompt.
 */

export const CATALOGUE_DIR = 'prompt-catalogue';

/** A unified diff of two texts, hunks only, with a little context. */
export function unifiedDiff(before: string, after: string, context = 2): string {
	const patch = createPatch('prompt', before, after, '', '', { context });
	const start = patch.indexOf('@@');
	return start === -1 ? '' : patch.slice(start).trimEnd();
}

const FENCE = '~~~~';

function fenced(text: string, language = 'text'): string {
	return `${FENCE}${language}\n${text}\n${FENCE}`;
}

function describeCombo(builder: Pick<Builder, 'axes'>, combo: Combo): string {
	return builder.axes.map((axis) => `${axis.id}=${combo[axis.id]}`).join(', ');
}

function conditionsLine(conditions: Record<string, string[]>): string {
	const entries = Object.entries(conditions);
	return entries.length === 0
		? 'Always.'
		: `Only when ${entries.map(([axis, values]) => `${axis} ∈ {${values.join(', ')}}`).join('; ')}.`;
}

function baselineFile(catalogue: Catalogue): string {
	return `# ${catalogue.builder.label}: the baseline prompt

${catalogue.builder.description}

Every other file in this folder is measured against this one. Combination:
\`${describeCombo(catalogue.builder, catalogue.baseline.combo)}\`

${fenced(catalogue.baseline.text)}
`;
}

function axesFile(builder: Builder, catalogue: Catalogue): string {
	const sections = builder.axes.map((axis) => {
		const values = sweeps(builder)
			.filter((sweep) => sweep.axis.id === axis.id)
			.map(({ value, combo }) => {
				const result = renderPrompt(builder.id, combo);
				if (!result.ok) {
					return `### ${axis.id} = ${value}\n\nNot a request any device could send from the baseline: ${result.problem}`;
				}
				const diff = unifiedDiff(catalogue.baseline.text, promptText(result.prompt));
				return `### ${axis.id} = ${value}\n\n${diff === '' ? 'No change.' : fenced(diff, 'diff')}`;
			});
		return `## ${axis.label} (\`${axis.id}\`, ${axis.kind}, baseline \`${axis.baseline}\`)\n\n${values.join('\n\n')}`;
	});
	return `# ${builder.label}: each axis against the baseline

One value changed at a time; see baseline.md for the prompt itself.

${sections.join('\n\n')}
`;
}

function paragraphsFile(catalogue: Catalogue): string {
	const entries = catalogue.paragraphs.map((paragraph) => {
		const where = paragraph.sweptOnly
			? 'only when one value was swept from the baseline'
			: `in ${paragraph.count} of ${catalogue.structuralTotal}`;
		return `## ¶ ${paragraph.id} · ${paragraph.roles.join(', ')} · ${where}

${conditionsLine(paragraph.conditions)}

${fenced(paragraph.text)}`;
	});
	const invalid =
		catalogue.invalid.length === 0
			? 'None.'
			: catalogue.invalid.map(({ problem, count }) => `- ${count} × ${problem}`).join('\n');
	return `# ${catalogue.builder.label}: every paragraph

${catalogue.paragraphs.length} distinct paragraphs, from ${catalogue.distinctPrompts} distinct prompts
over ${catalogue.structuralTotal} valid combinations of the structural axes, plus
each descriptive value swept from the baseline. Each paragraph is listed once,
in the order prompts put them, with the axis values it appears under.

Combinations skipped because no device could send them:

${invalid}

${entries.join('\n\n')}
`;
}

function lintFile(catalogues: readonly Catalogue[]): string {
	const sections = catalogues
		.filter((catalogue) => catalogue.lint.length > 0)
		.map((catalogue) => {
			const findings = catalogue.lint.map(
				(finding) =>
					`- **${finding.rule}** (${LINT_RULE_LABELS[finding.rule]}), in ${finding.count} prompts, e.g. \`${describeCombo(catalogue.builder, finding.example)}\`:\n  \`${finding.excerpt}\``
			);
			return `## ${catalogue.builder.label}\n\n${findings.join('\n')}`;
		});
	return `# Lint findings

Mechanical checks over every distinct prompt (\`lint.ts\`). A finding is for a
reviewer to judge, not a failure.

${sections.length === 0 ? 'None.' : sections.join('\n\n')}
`;
}

const README = `# Prompt catalogue

Generated by \`npm run prompts:export\`, and not committed: run it again for
what the prompt builders produce now. To see what a change does, copy this
folder aside before it and diff the two after.

For each builder (the story's replies, and each suggestion task):

- \`baseline.md\`: one whole prompt, every other file's point of comparison.
- \`axes.md\`: each axis value against the baseline, as a diff.
- \`paragraphs.md\`: every distinct paragraph of every prompt, once each, with
  the axis values it appears under: the place to review wording.
- \`catalogue.json\`: the same, for the debug page at /debug/prompts.

\`lint.md\` lists mechanical findings across all of them. User text is shown as
\`⟦placeholders⟧\`. See docs/prompt-review.md.
`;

/** Every file of the catalogue, by path under `CATALOGUE_DIR`, and the catalogues they came from. */
export function exportFiles(): { files: Map<string, string>; catalogues: Catalogue[] } {
	const files = new Map<string, string>([['README.md', README]]);
	const catalogues = BUILDERS.map((builder) => {
		const catalogue = buildCatalogue(builder);
		files.set(`${builder.id}/baseline.md`, baselineFile(catalogue));
		files.set(`${builder.id}/axes.md`, axesFile(builder, catalogue));
		files.set(`${builder.id}/paragraphs.md`, paragraphsFile(catalogue));
		files.set(`${builder.id}/catalogue.json`, `${JSON.stringify(catalogue, null, '\t')}\n`);
		return catalogue;
	});
	files.set('lint.md', lintFile(catalogues));
	return { files, catalogues };
}

/** Each builder's distinct prompts, one JSON line each, for grepping: too big to commit. */
export function fullExport(): Map<string, string> {
	return new Map(
		BUILDERS.map((builder) => {
			const seen = new Map<string, Combo[]>();
			const { structural, swept } = renderAll(builder);
			for (const { combo, text } of [...structural, ...swept]) {
				seen.set(text, [...(seen.get(text) ?? []), combo]);
			}
			const lines = [...seen].map(([text, combos]) => JSON.stringify({ combos, text }));
			return [`${builder.id}.jsonl`, `${lines.join('\n')}\n`];
		})
	);
}

/**
 * What a review is asked to look for, and how to read the files: the brief
 * `scripts/prompts-review.ts` gives Claude Code, and anyone else reviewing by
 * hand. Written into the review folder so the brief and the files it names
 * always go together.
 */
export const REVIEW_BRIEF = `# Reviewing the daydream prompts

You are reviewing the prompts a server sends to a language model, for an app
in which an adult user sets up and plays out interactive stories. The prompts
are built from many conditional pieces; this folder holds what they come to.
User text is shown as ⟦placeholders⟧: review the prompt's own words, not those.
The app's content is adult by design; judge the prompts as instructions to a
model, not the subject matter.

For each builder there is a folder holding:

- whole-NN.md: whole prompts, chosen so that between them they contain most of
  the builder's paragraphs and every structural option. Read these first and in
  full, as the model would: how good a section is depends on the rest of the
  prompt around it.
- in-context.md: every remaining paragraph, each with its section heading and
  its neighbours, from a prompt that has it.
- ../../<builder>/paragraphs.md: every distinct paragraph once, with the options
  it appears under, for checking that each appears exactly where it should.
- ../../<builder>/axes.md: each option against the baseline, as a diff.

Look for, in order of importance:

1. Instructions that contradict each other, including across sections and
   between what the prompt asks for and the answer format it gives.
2. Instructions a model could reasonably misread, and ones that are vague
   where it matters.
3. A paragraph that appears where it should not, or is missing where it
   should be (use the conditions in paragraphs.md), and dead branches.
4. Order: a step asked for before what it depends on.
5. Terms used inconsistently (one thing under two names, two things under one),
   and numbers written inconsistently.
6. Typos, grammar, and leftover spacing.

For each finding give: the builder; the file and a short quote; why it is a
problem, concretely; and a suggested rewrite. Rank findings by how much they
would change what the model writes. Say plainly when a builder has nothing
worth changing. Do not suggest changes to the user's placeholders, and do not
pad the review with praise or restate what the prompt does.
`;

/**
 * The files a review reads, by path under the review folder: the brief, and
 * per builder the whole prompts and the paragraphs in context
 * (`reviewSelection`). Not committed: they are derived from the snapshot.
 */
export function reviewFiles(): Map<string, string> {
	const files = new Map<string, string>([['BRIEF.md', REVIEW_BRIEF]]);
	for (const builder of BUILDERS) {
		const { whole, inContext } = reviewSelection(builder);
		whole.forEach((entry, index) => {
			files.set(
				`${builder.id}/whole-${String(index + 1).padStart(2, '0')}.md`,
				`# ${builder.label}: whole prompt ${index + 1} of ${whole.length}

Options: \`${describeCombo(builder, entry.combo)}\`
${index === 0 ? 'The baseline.' : `Adds ${entry.adds} paragraphs or options not in the prompts before it.`}

${fenced(entry.text)}
`
			);
		});
		const contexts = inContext.map(({ text, from }) => {
			const context = paragraphContext(from.prompt, text) ?? text;
			return `## From \`${describeCombo(builder, from.combo)}\`\n\nThe paragraph under review is between >>>> and <<<<.\n\n${fenced(context)}`;
		});
		files.set(
			`${builder.id}/in-context.md`,
			`# ${builder.label}: paragraphs not in a whole prompt

${contexts.length === 0 ? 'None: the whole prompts contain every paragraph.' : contexts.join('\n\n')}
`
		);
	}
	return files;
}
